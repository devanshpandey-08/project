def test_aes_encryption():
    """Test AES-256-GCM encryption/decryption."""
    if Encryptor is None:
        pytest.skip("Encryptor not available")
    
    encryptor = Encryptor()
    sensitive_data = {"credit_card": "4111111111111111", "ssn": "123-45-6789"}
    
    encrypted = encryptor.encrypt(json.dumps(sensitive_data))
    decrypted = json.loads(encryptor.decrypt(encrypted))
    
    assert decrypted == sensitive_data
    assert encrypted != json.dumps(sensitive_data)
    print("✅ AES-256 Encryption: Working")

def test_pii_redaction():
    """Test automatic PII detection and redaction."""
    if PIIDetector is None:
        pytest.skip("PIIDetector not available")
    
    detector = PIIDetector()
    text = "Contact john.doe@example.com or call +1-555-0199. SSN: 123-45-6789"
    
    redacted = detector.redact(text)
    
    assert "john.doe@example.com" not in redacted
    assert "[EMAIL]" in redacted
    print(f"✅ PII Redaction: {redacted}")

